We completed an expanded reconciliation of the 37301 FFM population against the 834 inbound automation data, comparing enrollee and policy identifiers across the available inbound history.

The updated analysis identified 4,395 exact Enrollee ID + Policy ID pairs present on both sides. These exact pairs represent 4,118 distinct enrollees and 4,335 distinct policies. The pair count is higher because an enrollee may be associated with multiple policies, and a policy may contain multiple household members.

For the remaining population, the largest patterns identified were 5,086 cross-issuer transitions (29.15%), where the same enrollee was found under another issuer lifecycle, and 3,764 different-lifecycle cases (21.58%), where the enrollee exists in inbound but the corresponding lifecycle differs. 3,307 pairs (18.96%) currently have no inbound enrollee evidence and require further validation.

One additional finding is that only 24 pairs (0.14%) were identified as potential policy-identifier mismatches, with only 5 pairs (0.03%) meeting the stricter same-transaction/different-policy criteria. This indicates that different policy IDs alone do not appear to be the primary driver of the reconciliation gap.

We are continuing to validate these categories against transaction history and UI evidence before finalizing the root-cause conclusions.
